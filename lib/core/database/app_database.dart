import 'package:drift/drift.dart';

import '../currency/currency_registry.dart';
import 'connection/native_connection.dart';
import 'tables.dart';

part 'app_database.g.dart';

/// The local database. Schema version 1 (Beta 0) created six tables
/// together in a single `onCreate` migration since there was no prior
/// production schema to migrate from — see
/// `STAGE1_BETA0_IMPLEMENTATION_PLAN.md` §6 for the full table-by-table
/// rationale and `docs/14_DECISION_LOG.md` ADR-020 for the
/// forward-compatibility decisions baked into that version. Schema
/// version 2 (Beta 1 Task 2) adds the `budgets` table via `onUpgrade` —
/// see ADR-021. Schema version 3 (Beta 1 Task 3) adds the
/// `savings_goals` and `savings_goal_contributions` tables via
/// `onUpgrade` — see ADR-022. Schema version 4 (Beta 1 Task 4A) adds the
/// `recurring_rules` and `recurring_occurrences` tables via `onUpgrade`
/// — see ADR-023. Schema version 5 (Beta 1 Task 4B) adds the
/// `notifications_enabled` column to `recurring_rules` via `onUpgrade`
/// — see ADR-024. Schema version 6 (Checkpoint 8.1, Premium Theme
/// Personalization Foundation) adds the `theme_preference` column to
/// `profiles` via `onUpgrade` — a single defaulted `TextColumn` storing
/// one of `AppThemeStyle.storageValue` ('light'/'dark'/'pink'/'ocean'/
/// 'forest'; see `lib/shared/theme/app_theme_style.dart`), backfilled to
/// `'light'` on every existing row so no installed app's appearance
/// changes on upgrade. This is the ONLY schema change CP8.1 makes —
/// UI-personalization preference storage genuinely required a new
/// column (Beta 0 has no other key-value preference store; see
/// `pubspec.yaml`'s dependency list), so this migration was not
/// avoidable, but it is additive, non-destructive, and touches no
/// financial table. Schema version 7 (Checkpoint 9.3, Persistent
/// Reference FX Cache) adds the `reference_exchange_rates` table via
/// `onUpgrade` — see `docs/14_DECISION_LOG.md` ADR-011's persistent-cache
/// follow-up note and `lib/core/database/tables.dart`'s
/// `ReferenceExchangeRates` doc comment. This is purely additive: no
/// existing table changes shape, and no historical/financial data is
/// touched. `ReferenceExchangeRates` is architecturally independent of
/// `TransactionExchangeRates` — see that class's doc for why the two must
/// never be confused. Schema version 8 (Checkpoint 12.2, Cloud
/// Identity / Auth Foundation) adds the `cloud_account_links` table --
/// see `lib/core/database/tables.dart`'s `CloudAccountLinks` doc for the
/// full rationale, including why it deliberately has no `deleted_at`/
/// `sync_version`/`sync_status` (it is device-local link bookkeeping,
/// never synced user data) and why its primary key is the natural
/// `profile_id` rather than a surrogate `id`. Purely additive: no
/// existing table changes shape, and no financial data is read,
/// rewritten, or deleted by this migration.
///
/// `app_database.g.dart` (referenced by the `part` directive above) is
/// generated by `dart run build_runner build` — see
/// `CLAUDE_FIRST_CODING_PROMPT.md` for why it could not be generated
/// inside the sandbox that wrote this file, and exactly what to run
/// locally.
@DriftDatabase(
  tables: <Type>[
    Currencies,
    Profiles,
    Categories,
    Accounts,
    FinancialInstitutions,
    PaymentInstruments,
    CreditFacilityDetails,
    DepositDetails,
    Transactions,
    TransactionExchangeRates,
    Budgets,
    SavingsGoals,
    SavingsGoalContributions,
    RecurringRules,
    RecurringOccurrences,
    ReferenceExchangeRates,
    CloudAccountLinks,
    ChequeBooks,
    Cheques,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase([QueryExecutor? executor]) : super(executor ?? openAppDatabaseConnection());

  /// Used by tests to inject an in-memory or temp-file executor. See
  /// `test/core/database/`.
  AppDatabase.forTesting(super.executor);

  @override
  int get schemaVersion => 15;

  /// v1 -> v2 (Beta 1 Task 2): adds the `budgets` table. No existing
  /// table changes shape and no historical data is touched -- see
  /// `docs/14_DECISION_LOG.md` ADR-021.
  ///
  /// v2 -> v3 (Beta 1 Task 3): adds the `savings_goals` and
  /// `savings_goal_contributions` tables. No existing table changes
  /// shape and no historical data is touched -- see
  /// `docs/14_DECISION_LOG.md` ADR-022.
  ///
  /// v3 -> v4 (Beta 1 Task 4A): adds the `recurring_rules` and
  /// `recurring_occurrences` tables. No existing table changes shape and
  /// no historical data is touched -- see `docs/14_DECISION_LOG.md`
  /// ADR-023.
  ///
  /// v4 -> v5 (Beta 1 Task 4B): adds the `notifications_enabled` column
  /// (`BoolColumn`, default `false`) to `recurring_rules`. Every
  /// existing row backfills to `false` -- nobody is retroactively
  /// opted in to local reminder notifications. No other table changes
  /// shape and no historical data is touched -- see
  /// `docs/14_DECISION_LOG.md` ADR-024.
  ///
  /// v5 -> v6 (Checkpoint 8.1): adds the `theme_preference` column
  /// (`TextColumn`, default `'light'`) to `profiles`. Every existing row
  /// backfills to `'light'` -- the exact same value `AppThemeStyle
  /// .fallback` resolves to at read time, so no installed app's
  /// appearance changes on upgrade. `profiles` is an original v1 table
  /// (created once, in `onCreate`'s `m.createAll()`) and is never
  /// (re)created inside `onUpgrade` at any version threshold -- unlike
  /// `recurringRules` above, there is no "was this table just created
  /// with the column already present" ambiguity to guard against here,
  /// so this is a single unconditional `addColumn` for every `from < 6`
  /// database. No other table changes shape and no financial data is
  /// touched.
  ///
  /// v6 -> v7 (Checkpoint 9.3): adds the `reference_exchange_rates` table
  /// (see `tables.dart`'s `ReferenceExchangeRates` doc for the full
  /// rationale, including why its primary key is the composite
  /// `(baseCurrency, quoteCurrency)` pair rather than a surrogate `id`
  /// like every other table here). Purely additive -- no existing table
  /// changes shape, no row in any existing table is read, rewritten, or
  /// deleted, and `transaction_exchange_rates` (the historical snapshot
  /// table) is completely untouched by this step.
  ///
  /// v7 -> v8 (Checkpoint 12.2): adds the `cloud_account_links` table
  /// (see `tables.dart`'s `CloudAccountLinks` doc for the full
  /// rationale). Purely additive -- no existing table changes shape, no
  /// row in any existing table is read, rewritten, or deleted. No
  /// backfill: a database upgrading from before v8 has zero rows in the
  /// new table (every existing install is, by definition, local-only /
  /// not linked to any cloud account yet -- there is nothing to
  /// backfill it with).
  ///
  /// Schema version 9 (Checkpoint B, unified `FinancialAccount`
  /// classification foundation) adds `balance_class`, `subtype`, and
  /// `institution_id` to `accounts`, folds in the already-committed
  /// `accounts.sync_version`/`accounts.sync_status` gap from
  /// `docs/21_CLOUD_SYNC_ARCHITECTURE.md` §11 / ADR-032 into this same
  /// version bump (per `docs/20_ACCOUNTS_ASSETS_HOUSEHOLD_ARCHITECTURE
  /// .md` §13.1's explicit instruction not to migrate `accounts`
  /// twice), and adds the new `financial_institutions` table -- see
  /// `docs/14_DECISION_LOG.md` ADR-035 and `tables.dart`'s
  /// `FinancialInstitutions`/`Accounts` doc comments for the full
  /// rationale. Every pre-existing `accounts` row is conservatively
  /// backfilled: `balance_class` becomes `'asset'` for every row with
  /// NO exception (a legacy `type: 'card'` row is never guessed as a
  /// liability), and `subtype` becomes `'cash'`/`'bank'`/`'wallet'` for
  /// the three unambiguous legacy `type` strings, `'legacyCardNeeds
  /// Review'` for `'card'`, or the conservative fallback
  /// `'legacyUnknownNeedsReview'` (already the column's default -- see
  /// `Accounts.subtype`'s doc) for any other/unrecognized legacy `type`
  /// string. No existing `accounts` row's `id`/`name`/`type`/
  /// `currencyCode`/`openingBalanceMinorUnits`/`isActive`/`createdAt`/
  /// `updatedAt`/`deletedAt` is read, rewritten, or reinterpreted by
  /// this migration, no `transactions` row is touched at all, and zero
  /// `financial_institutions` rows are created (institution assignment
  /// is a later checkpoint's UI, not this one's).
  ///
  /// Schema version 10 (Checkpoint D, PaymentInstrument foundation) adds
  /// the new `payment_instruments` table and one nullable
  /// `transactions.payment_instrument_id` column -- see
  /// `tables.dart`'s `PaymentInstruments`/`Transactions.paymentInstrumentId`
  /// doc comments for the full rationale. Purely additive: no existing
  /// table changes shape, `accounts`/its classification from Checkpoint
  /// B is completely untouched, every pre-existing `transactions` row
  /// gets `payment_instrument_id = null`, and zero `payment_instruments`
  /// rows are fabricated. `FinanceEngine` is not touched by this
  /// checkpoint at all.
  ///
  /// Schema version 11 (Checkpoint E, credit-facility metadata) adds the
  /// new `credit_facility_details` table only -- see `tables.dart`'s
  /// `CreditFacilityDetails` doc comment for the full rationale. Purely
  /// additive: no existing table changes shape, no existing row in
  /// `accounts`/`transactions`/`payment_instruments` is read, rewritten,
  /// or deleted, and zero `credit_facility_details` rows are fabricated
  /// for any pre-existing account -- this migration never guesses that a
  /// legacy or Checkpoint-B-classified account is a credit facility
  /// (docs/20 §13.1's "never auto-convert" policy extends to this table
  /// too). `FinanceEngine`/`TransactionRepository`'s expense/transfer
  /// insert path are not touched by this migration itself -- Checkpoint
  /// E's one behavior change (payment-instrument attribution requiring
  /// `instrumentType: creditCard` when the target account is a
  /// liability) lives in `TransactionRepository` source code, not in
  /// this schema migration.
  ///
  /// Schema version 12 (Checkpoint F, deposit metadata) adds the new
  /// `deposit_details` table only -- see `tables.dart`'s `DepositDetails`
  /// doc comment for the full rationale. Purely additive, in exactly the
  /// same shape as Checkpoint E's own v10 -> v11 step: no existing table
  /// changes shape, no existing row in any table is read, rewritten, or
  /// deleted, and zero `deposit_details` rows are fabricated for any
  /// pre-existing account -- this migration never guesses that a legacy
  /// or Checkpoint-B-classified account is a deposit (docs/20 §13.1's
  /// "never auto-convert" policy extends to this table too, and this
  /// checkpoint's own brief repeats it explicitly: "no automatic
  /// conversion of legacy savings/bank accounts into deposits").
  /// `FinanceEngine` and `TransactionRepository.recordExpense`/
  /// `recordIncome`/`recordTransfer` are not touched by this migration OR
  /// by any source-code change in this checkpoint at all -- funding a
  /// deposit (an asset-to-asset transfer), a maturity principal
  /// movement (transfer-like), and posting interest (income) are every
  /// one of them already expressible with the existing, unmodified
  /// `recordTransfer`/`recordIncome` methods against a `subtype: deposit`
  /// account, exactly as Checkpoint E discovered for a liability
  /// `creditCard` account -- neither method has ever branched on
  /// `subtype` at all.
  /// Schema version 13 (Checkpoint N, Cheque/Check Management) adds the
  /// new `cheque_books` and `cheques` tables only -- see `tables.dart`'s
  /// `ChequeBooks`/`Cheques` doc comments for the full rationale and
  /// `docs/20_ACCOUNTS_ASSETS_HOUSEHOLD_ARCHITECTURE.md` §13.16 for the
  /// accounting-semantics audit this checkpoint performed before
  /// choosing this shape. Purely additive, in exactly the same shape as
  /// Checkpoint E's/F's own v10 -> v11 / v11 -> v12 steps: no existing
  /// table changes shape, no existing row in any table is read,
  /// rewritten, or deleted, and zero `cheque_books`/`cheques` rows are
  /// fabricated for any pre-existing account. `FinanceEngine` and every
  /// dashboard/net-worth provider are not touched by this migration OR
  /// by any source-code change in this checkpoint at all -- a cleared
  /// cheque's accounting effect is exactly one ordinary `Transactions`
  /// row (an expense for an issued cheque, an income for a received
  /// one), created through the completely unmodified
  /// `TransactionRepository.recordExpense`/`recordIncome`, exactly the
  /// same "no FinanceEngine change needed" discovery Checkpoint E/F
  /// already made for `creditCard`/`deposit` accounts. A pending cheque
  /// never creates a `Transactions` row at all, so it is invisible to
  /// every balance/available-money/net-worth calculation by
  /// construction, not by any new filtering logic.
  ///
  /// Schema version 14 (Checkpoint U1, Category, Service, Currency &
  /// Card Visual Identity Foundation) adds one nullable `color_key`
  /// column to `categories` only -- see `tables.dart`'s
  /// `Categories.colorKey` doc comment for the full rationale. This is
  /// the ONE genuine schema change U1 makes: the pre-checkpoint audit
  /// found `categories.icon` and `payment_instruments.network` already
  /// persisted (see `docs/14_DECISION_LOG.md` ADR-044), but no column
  /// anywhere stores a category's color, and no other mechanism (a
  /// second table, a derived value) does either. Purely additive: no
  /// existing table changes shape, no existing row in any other table
  /// is read, rewritten, or deleted. The 8 pre-existing seeded system
  /// categories (`CategoryRepository._systemCategories`) are backfilled
  /// to a fixed, deterministic color each -- matching this checkpoint's
  /// own "system categories get deterministic, never random, visual
  /// identity" requirement -- via literal `UPDATE ... WHERE id =
  /// 'sys-...'` statements keyed by their fixed seed ids, exactly the
  /// same "frozen literal, not computed from a live enum" discipline
  /// Checkpoint B's v8 -> v9 step already established for
  /// `accounts.subtype` (see that step's own comment below for why: a
  /// shipped migration must keep working even if `CategoryColorKey` is
  /// refactored later). Every OTHER pre-existing `categories` row
  /// (every user-created category, on every profile) is deliberately
  /// left with `color_key = null` -- `categoryColorFor` resolves `null`
  /// to a deterministic-per-category-id fallback color at read time
  /// (see that function's doc comment), so backfilling every user row
  /// here would add migration complexity for a case the resolver
  /// already handles safely and consistently.
  ///
  /// Schema version 15 (Checkpoint U2, Service / Merchant Identity
  /// Integration & App-Wide Financial Visual Consistency) adds one
  /// nullable `service_identity_key` column to `transactions` AND to
  /// `recurring_rules` -- see `Transactions.serviceIdentityKey`'s own
  /// doc comment in `tables.dart` for the full rationale (a service
  /// identity like "Netflix" is independent of, and never replaces,
  /// `categoryId`). Purely additive: no existing column changes shape,
  /// no existing row anywhere is read, rewritten, or deleted, and every
  /// pre-existing transaction/rule simply gets `service_identity_key =
  /// null` ("no service identity") via the column's own nullability --
  /// correct historical meaning, so no backfill statement is needed.
  /// `recurring_occurrences` is untouched: an occurrence's service
  /// identity is always inherited from the rule/transaction it points
  /// to, never a copy of its own.
  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (Migrator m) async {
          await m.createAll();
          await _seedCurrencies();
        },
        onUpgrade: (Migrator m, int from, int to) async {
          if (from < 2) {
            await m.createTable(budgets);
          }
          if (from < 3) {
            await m.createTable(savingsGoals);
            await m.createTable(savingsGoalContributions);
          }
          if (from < 4) {
            // recurringRules/recurringOccurrences here are Drift's
            // generated table objects, which always reflect the CURRENT
            // schema in code -- not a historical v4 snapshot. That means
            // this createTable call already includes the v5
            // `notifications_enabled` column, so a database upgrading
            // from before v4 must NOT also go through the v4 -> v5
            // addColumn step below (that would try to add the same
            // column twice and fail with "duplicate column name").
            await m.createTable(recurringRules);
            await m.createTable(recurringOccurrences);
          } else if (from == 4) {
            // Only a database that genuinely already had the v4
            // recurring_rules table (created without
            // notifications_enabled, before this column existed) needs
            // it added here.
            await m.addColumn(recurringRules, recurringRules.notificationsEnabled);
          }
          if (from < 6) {
            await m.addColumn(profiles, profiles.themePreference);
          }
          if (from < 7) {
            await m.createTable(referenceExchangeRates);
          }
          if (from < 8) {
            await m.createTable(cloudAccountLinks);
          }
          if (from < 9) {
            // Checkpoint B -- see the doc comment above `schemaVersion`
            // for the full rationale. Additive-only: every statement
            // below either adds a new nullable/defaulted column, adds a
            // brand-new empty table, or corrects a just-added column's
            // value on a per-row basis. No existing column changes
            // shape, no existing row is deleted, and `transactions` is
            // never touched.
            await m.createTable(financialInstitutions);
            await m.addColumn(accounts, accounts.balanceClass);
            await m.addColumn(accounts, accounts.subtype);
            await m.addColumn(accounts, accounts.institutionId);
            await m.addColumn(accounts, accounts.syncVersion);
            await m.addColumn(accounts, accounts.syncStatus);
            // `accounts.balanceClass` already defaulted every row to
            // 'asset' via the `addColumn` above -- correct here per
            // docs/20 §13.1: no row is EVER corrected to 'liability' by
            // this migration. `accounts.subtype` already defaulted
            // every row to 'legacyUnknownNeedsReview' via the
            // `addColumn` above; the four statements below correct it
            // for every row whose legacy `type` is one of the three
            // unambiguous values or the one genuinely ambiguous 'card'
            // value -- any other/unrecognized `type` string is left at
            // the conservative default. These string literals
            // intentionally are NOT computed from
            // `lib/core/finance/financial_account_subtype.dart`'s
            // `FinancialAccountSubtype` enum -- a shipped migration
            // must remain a frozen, self-contained historical artifact
            // that keeps working even if that enum is refactored later.
            // `financial_account_classification_migration_test.dart`
            // asserts these literals match the enum's current values.
            await customStatement("UPDATE accounts SET subtype = 'cash' WHERE type = 'cash'");
            await customStatement("UPDATE accounts SET subtype = 'bank' WHERE type = 'bank'");
            await customStatement("UPDATE accounts SET subtype = 'wallet' WHERE type = 'wallet'");
            await customStatement(
              "UPDATE accounts SET subtype = 'legacyCardNeedsReview' WHERE type = 'card'",
            );
          }
          if (from < 10) {
            // Checkpoint D -- see the doc comment above `schemaVersion`
            // for the full rationale. Additive-only: a brand-new empty
            // table plus one nullable column on `transactions`. No
            // existing table changes shape, no existing row in any
            // table is read, rewritten, or deleted, and zero
            // `payment_instruments` rows are fabricated -- every
            // pre-existing `transactions` row simply gets
            // `payment_instrument_id = null` via the column's own
            // nullability (no backfill statement is needed or run).
            await m.createTable(paymentInstruments);
            await m.addColumn(transactions, transactions.paymentInstrumentId);
          }
          if (from < 11) {
            // Checkpoint E -- see the doc comment above `schemaVersion`
            // for the full rationale. Additive-only: one brand-new,
            // empty table. No existing table changes shape, no existing
            // row anywhere is read, rewritten, or deleted, and zero
            // `credit_facility_details` rows are fabricated for any
            // pre-existing account.
            await m.createTable(creditFacilityDetails);
          }
          if (from < 12) {
            // Checkpoint F -- see the doc comment above `schemaVersion`
            // for the full rationale. Additive-only: one brand-new,
            // empty table -- the identical shape as the v10 -> v11 step
            // immediately above, and for the identical reason it cannot
            // fail against any historical fixture: a pure `CREATE TABLE`
            // only needs its FK targets (`accounts`/`profiles`), which
            // every fixture already has. No existing row anywhere is
            // read, rewritten, or deleted, and zero `deposit_details`
            // rows are fabricated for any pre-existing account.
            await m.createTable(depositDetails);
          }
          if (from < 13) {
            // Checkpoint N -- see the doc comment above `schemaVersion`
            // for the full rationale. Additive-only: two brand-new,
            // empty tables -- the identical shape as the v10 -> v11 /
            // v11 -> v12 steps immediately above, and for the identical
            // reason neither can fail against any historical fixture: a
            // pure `CREATE TABLE` only needs its FK targets
            // (`accounts`/`profiles`/`transactions`), which every
            // fixture already has. `cheques` is created after
            // `chequeBooks` since it references it. No existing row
            // anywhere is read, rewritten, or deleted, and zero
            // `cheque_books`/`cheques` rows are fabricated for any
            // pre-existing account.
            await m.createTable(chequeBooks);
            await m.createTable(cheques);
          }
          if (from < 14) {
            // Checkpoint U1 -- see the doc comment above `migration`
            // for the full rationale. Additive-only: one nullable
            // `TextColumn` on `categories`. No existing table changes
            // shape, no existing row in any OTHER table is read,
            // rewritten, or deleted, and no `transactions`/`budgets`/
            // `recurring_rules`/any financial table is touched at all.
            //
            // Every pre-existing `categories` row gets `color_key = null`
            // via the column's own nullability (no backfill statement is
            // needed for that default) EXCEPT the 8 fixed-id seeded
            // system categories, which are backfilled below to a
            // deterministic color each -- literal id/value pairs, not
            // computed from `CategoryColorKey`, so this step keeps
            // working even if that enum's declared order or entries
            // change later. `category_color_migration_test.dart` asserts
            // these literals resolve to a real `CategoryColorKey.storageValue`.
            await m.addColumn(categories, categories.colorKey);
            await customStatement("UPDATE categories SET color_key = 'green' WHERE id = 'sys-groceries'");
            await customStatement("UPDATE categories SET color_key = 'blue' WHERE id = 'sys-transport'");
            await customStatement("UPDATE categories SET color_key = 'amber' WHERE id = 'sys-bills'");
            await customStatement("UPDATE categories SET color_key = 'orange' WHERE id = 'sys-dining'");
            await customStatement("UPDATE categories SET color_key = 'red' WHERE id = 'sys-health'");
            await customStatement("UPDATE categories SET color_key = 'slate' WHERE id = 'sys-other-expense'");
            await customStatement("UPDATE categories SET color_key = 'teal' WHERE id = 'sys-salary'");
            await customStatement("UPDATE categories SET color_key = 'lime' WHERE id = 'sys-other-income'");
          }
          if (from < 15) {
            // Checkpoint U2 -- see the doc comment above `migration`
            // for the full rationale. Additive-only: one nullable
            // `TextColumn` on `transactions`, and the same on
            // `recurring_rules`. No existing column changes shape, no
            // existing row anywhere is read, rewritten, or deleted, and
            // every pre-existing row simply gets `service_identity_key =
            // null` via the column's own nullability -- correct
            // historical meaning ("no service identity") for every
            // transaction/rule that predates this feature, so no
            // backfill statement is needed or run.
            //
            // `transactions` is a v1 base table -- always present by the
            // time any `onUpgrade` call reaches here, for any `from`.
            await m.addColumn(transactions, transactions.serviceIdentityKey);
            //
            // `recurring_rules`, by contrast, is NOT a v1 base table --
            // it's created by the `from < 4` branch above using drift's
            // CURRENT generated table object, which (now that
            // `RecurringRules.serviceIdentityKey` exists in
            // `tables.dart`) already includes this column the moment
            // it's created -- the exact same "createTable already has
            // it, addColumn would double-add it" hazard this file's own
            // `from < 4` / `from == 4` split already documents for
            // `notifications_enabled`. So: for `from < 4`, the table was
            // just created a few lines above already including this
            // column -- nothing more to do. For `from >= 4`,
            // `recurring_rules` has existed since a version that
            // predates this column, so it genuinely needs the
            // `addColumn` below.
            if (from >= 4) {
              await m.addColumn(recurringRules, recurringRules.serviceIdentityKey);
            }
          }
        },
      );

  /// Seeds the `currencies` table from [CurrencyRegistry.seed] on first
  /// database creation. `insertOrIgnore` makes this safe to call more
  /// than once without erroring on the primary-key conflict.
  Future<void> _seedCurrencies() async {
    await batch((Batch b) {
      b.insertAll(
        currencies,
        CurrencyRegistry.seed.map(
          (currency) => CurrenciesCompanion.insert(
            code: currency.code,
            displayName: currency.displayName,
            symbol: currency.symbol,
            minorUnits: currency.minorUnits,
            isActive: Value<bool>(currency.isActive),
          ),
        ),
        mode: InsertMode.insertOrIgnore,
      );
    });
  }
}
