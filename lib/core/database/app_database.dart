import '../currency/currency_registry.dart';
import 'connection/native_connection.dart';
import 'tables.dart';

part 'app_database.g.dart';

/// The local database. Schema version 1 (Beta 0) created six tables
/// together in a single `onCreate` migration since there was no prior
/// production schema to migrate from — see
/// `STAGE1_BETA0_IMPLEMENTATION_PLAN.md` §6 for the full table-by-table
/// rationale and `docs/14_DECISION_LOG.md` ADR-020 for the
/// forward-compatibility decisions baked into that version. Schema
/// version 2 (Beta 1 Task 2) adds the `budgets` table via `onUpgrade` —
/// see ADR-021. Schema version 3 (Beta 1 Task 3) adds the
/// `savings_goals` and `savings_goal_contributions` tables via
/// `onUpgrade` — see ADR-022. Schema version 4 (Beta 1 Task 4A) adds the
/// `recurring_rules` and `recurring_occurrences` tables via `onUpgrade`
/// — see ADR-023. Schema version 5 (Beta 1 Task 4B) adds the
/// `notifications_enabled` column to `recurring_rules` via `onUpgrade`
/// — see ADR-024. Schema version 6 (Checkpoint 8.1, Premium Theme
/// Personalization Foundation) adds the `theme_preference` column to
/// `profiles` via `onUpgrade` — a single defaulted `TextColumn` storing
/// one of `AppThemeStyle.storageValue` ('light'/'dark'/'pink'/'ocean'/
/// 'forest'; see `lib/shared/theme/app_theme_style.dart`), backfilled to
/// `'light'` on every existing row so no installed app's appearance
/// changes on upgrade. This is the ONLY schema change CP8.1 makes —
/// UI-personalization preference storage genuinely required a new
/// column (Beta 0 has no other key-value preference store; see
/// `pubspec.yaml`'s dependency list), so this migration was not
/// avoidable, but it is additive, non-destructive, and touches no
/// financial table. Schema version 7 (Checkpoint 9.3, Persistent
/// Reference FX Cache) adds the `reference_exchange_rates` table via
/// `onUpgrade` — see `docs/14_DECISION_LOG.md` ADR-011's persistent-cache
/// follow-up note and `lib/core/database/tables.dart`'s
/// `ReferenceExchangeRates` doc comment. This is purely additive: no
/// existing table changes shape, and no historical/financial data is
/// touched. `ReferenceExchangeRates` is architecturally independent of
/// `TransactionExchangeRates` — see that class's doc for why the two must
/// never be confused. Schema version 8 (Checkpoint 12.2, Cloud
/// Identity / Auth Foundation) adds the `cloud_account_links` table --
/// see `lib/core/database/tables.dart`'s `CloudAccountLinks` doc for the
/// full rationale, including why it deliberately has no `deleted_at`/
/// `sync_version`/`sync_status` (it is device-local link bookkeeping,
/// never synced user data) and why its primary key is the natural
/// `profile_id` rather than a surrogate `id`. Purely additive: no
/// existing table changes shape, and no financial data is read,
/// rewritten, or deleted by this migration.
///
/// `app_database.g.dart` (referenced by the `part` directive above) is
/// generated by `dart run build_runner build` — see
/// `CLAUDE_FIRST_CODING_PROMPT.md` for why it could not be generated
/// inside the sandbox that wrote this file, and exactly what to run
/// locally.
@DriftDatabase(
  tables: <Type>[
    Currencies,
    Profiles,
    Categories,
    Accounts,
    FinancialInstitutions,
    Transactions,
    TransactionExchangeRates,
    Budgets,
    SavingsGoals,
    SavingsGoalContributions,
    RecurringRules,
    RecurringOccurrences,
    ReferenceExchangeRates,
    CloudAccountLinks,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase([QueryExecutor? executor]) : super(executor ?? openAppDatabaseConnection());

  /// Used by tests to inject an in-memory or temp-file executor. See
  /// `test/core/database/`.
  AppDatabase.forTesting(super.executor);

  @override
  int get schemaVersion => 9;

  /// v1 -> v2 (Beta 1 Task 2): adds the `budgets` table. No existing
  /// table changes shape and no historical data is touched -- see
  /// `docs/14_DECISION_LOG.md` ADR-021.
  ///
  /// v2 -> v3 (Beta 1 Task 3): adds the `savings_goals` and
  /// `savings_goal_contributions` tables. No existing table changes
  /// shape and no historical data is touched -- see
  /// `docs/14_DECISION_LOG.md` ADR-022.
  ///
  /// v3 -> v4 (Beta 1 Task 4A): adds the `recurring_rules` and
  /// `recurring_occurrences` tables. No existing table changes shape and
  /// no historical data is touched -- see `docs/14_DECISION_LOG.md`
  /// ADR-023.
  ///
  /// v4 -> v5 (Beta 1 Task 4B): adds the `notifications_enabled` column
  /// (`BoolColumn`, default `false`) to `recurring_rules`. Every
  /// existing row backfills to `false` -- nobody is retroactively
  /// opted in to local reminder notifications. No other table changes
  /// shape and no historical data is touched -- see
  /// `docs/14_DECISION_LOG.md` ADR-024.
  ///
  /// v5 -> v6 (Checkpoint 8.1): adds the `theme_preference` column
  /// (`TextColumn`, default `'light'`) to `profiles`. Every existing row
  /// backfills to `'light'` -- the exact same value `AppThemeStyle
  /// .fallback` resolves to at read time, so no installed app's
  /// appearance changes on upgrade. `profiles` is an original v1 table
  /// (created once, in `onCreate`'s `m.createAll()`) and is never
  /// (re)created inside `onUpgrade` at any version threshold -- unlike
  /// `recurringRules` above, there is no "was this table just created
  /// with the column already present" ambiguity to guard against here,
  /// so this is a single unconditional `addColumn` for every `from < 6`
  /// database. No other table changes shape and no financial data is
  /// touched.
  ///
  /// v6 -> v7 (Checkpoint 9.3): adds the `reference_exchange_rates` table
  /// (see `tables.dart`'s `ReferenceExchangeRates` doc for the full
  /// rationale, including why its primary key is the composite
  /// `(baseCurrency, quoteCurrency)` pair rather than a surrogate `id`
  /// like every other table here). Purely additive -- no existing table
  /// changes shape, no row in any existing table is read, rewritten, or
  /// deleted, and `transaction_exchange_rates` (the historical snapshot
  /// table) is completely untouched by this step.
  ///
  /// v7 -> v8 (Checkpoint 12.2): adds the `cloud_account_links` table
  /// (see `tables.dart`'s `CloudAccountLinks` doc for the full
  /// rationale). Purely additive -- no existing table changes shape, no
  /// row in any existing table is read, rewritten, or deleted. No
  /// backfill: a database upgrading from before v8 has zero rows in the
  /// new table (every existing install is, by definition, local-only /
  /// not linked to any cloud account yet -- there is nothing to
  /// backfill it with).
  ///
  /// Schema version 9 (Checkpoint B, unified `FinancialAccount`
  /// classification foundation) adds `balance_class`, `subtype`, and
  /// `institution_id` to `accounts`, folds in the already-committed
  /// `accounts.sync_version`/`accounts.sync_status` gap from
  /// `docs/21_CLOUD_SYNC_ARCHITECTURE.md` §11 / ADR-032 into this same
  /// version bump (per `docs/20_ACCOUNTS_ASSETS_HOUSEHOLD_ARCHITECTURE
  /// .md` §13.1's explicit instruction not to migrate `accounts`
  /// twice), and adds the new `financial_institutions` table -- see
  /// `docs/14_DECISION_LOG.md` ADR-035 and `tables.dart`'s
  /// `FinancialInstitutions`/`Accounts` doc comments for the full
  /// rationale. Every pre-existing `accounts` row is conservatively
  /// backfilled: `balance_class` becomes `'asset'` for every row with
  /// NO exception (a legacy `type: 'card'` row is never guessed as a
  /// liability), and `subtype` becomes `'cash'`/`'bank'`/`'wallet'` for
  /// the three unambiguous legacy `type` strings, `'legacyCardNeeds
  /// Review'` for `'card'`, or the conservative fallback
  /// `'legacyUnknownNeedsReview'` (already the column's default -- see
  /// `Accounts.subtype`'s doc) for any other/unrecognized legacy `type`
  /// string. No existing `accounts` row's `id`/`name`/`type`/
  /// `currencyCode`/`openingBalanceMinorUnits`/`isActive`/`createdAt`/
  /// `updatedAt`/`deletedAt` is read, rewritten, or reinterpreted by
  /// this migration, no `transactions` row is touched at all, and zero
  /// `financial_institutions` rows are created (institution assignment
  /// is a later checkpoint's UI, not this one's).
  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (Migrator m) async {
          await m.createAll();
          await _seedCurrencies();
        },
        onUpgrade: (Migrator m, int from, int to) async {
          if (from < 2) {
            await m.createTable(budgets);
          }
          if (from < 3) {
            await m.createTable(savingsGoals);
            await m.createTable(savingsGoalContributions);
          }
          if (from < 4) {
            // recurringRules/recurringOccurrences here are Drift's
            // generated table objects, which always reflect the CURRENT
            // schema in code -- not a historical v4 snapshot. That means
            // this createTable call already includes the v5
            // `notifications_enabled` column, so a database upgrading
            // from before v4 must NOT also go through the v4 -> v5
            // addColumn step below (that would try to add the same
            // column twice and fail with "duplicate column name").
            await m.createTable(recurringRules);
            await m.createTable(recurringOccurrences);
          } else if (from == 4) {
            // Only a database that genuinely already had the v4
            // recurring_rules table (created without
            // notifications_enabled, before this column existed) needs
            // it added here.
            await m.addColumn(recurringRules, recurringRules.notificationsEnabled);
          }
          if (from < 6) {
            await m.addColumn(profiles, profiles.themePreference);
          }
          if (from < 7) {
            await m.createTable(referenceExchangeRates);
          }
          if (from < 8) {
            await m.createTable(cloudAccountLinks);
          }
          if (from < 9) {
            // Checkpoint B -- see the doc comment above `schemaVersion`
            // for the full rationale. Additive-only: every statement
            // below either adds a new nullable/defaulted column, adds a
            // brand-new empty table, or corrects a just-added column's
            // value on a per-row basis. No existing column changes
            // shape, no existing row is deleted, and `transactions` is
            // never touched.
            await m.createTable(financialInstitutions);
            await m.addColumn(accounts, accounts.balanceClass);
            await m.addColumn(accounts, accounts.subtype);
            await m.addColumn(accounts, accounts.institutionId);
            await m.addColumn(accounts, accounts.syncVersion);
            await m.addColumn(accounts, accounts.syncStatus);
            // `accounts.balanceClass` already defaulted every row to
            // 'asset' via the `addColumn` above -- correct here per
            // docs/20 §13.1: no row is EVER corrected to 'liability' by
            // this migration. `accounts.subtype` already defaulted
            // every row to 'legacyUnknownNeedsReview' via the
            // `addColumn` above; the four statements below correct it
            // for every row whose legacy `type` is one of the three
            // unambiguous values or the one genuinely ambiguous 'card'
            // value -- any other/unrecognized `type` string is left at
            // the conservative default. These string literals
            // intentionally are NOT computed from
            // `lib/core/finance/financial_account_subtype.dart`'s
            // `FinancialAccountSubtype` enum -- a shipped migration
            // must remain a frozen, self-contained historical artifact
            // that keeps working even if that enum is refactored later.
            // `financial_account_classification_migration_test.dart`
            // asserts these literals match the enum's current values.
            await customStatement("UPDATE accounts SET subtype = 'cash' WHERE type = 'cash'");
            await customStatement("UPDATE accounts SET subtype = 'bank' WHERE type = 'bank'");
            await customStatement("UPDATE accounts SET subtype = 'wallet' WHERE type = 'wallet'");
            await customStatement(
              "UPDATE accounts SET subtype = 'legacyCardNeedsReview' WHERE type = 'card'",
            );
          }
        },
      );

  /// Seeds the `currencies` table from [CurrencyRegistry.seed] on first
  /// database creation. `insertOrIgnore` makes this safe to call more
  /// than once without erroring on the primary-key conflict.
  Future<void> _seedCurrencies() async {
    await batch((Batch b) {
      b.insertAll(
        currencies,
        CurrencyRegistry.seed.map(
          (currency) => CurrenciesCompanion.insert(
            code: currency.code,
            displayName: currency.displayName,
            symbol: currency.symbol,
            minorUnits: currency.minorUnits,
            isActive: Value<bool>(currency.isActive),
          ),
        ),
        mode: InsertMode.insertOrIgnore,
      );
    });
  }
}
