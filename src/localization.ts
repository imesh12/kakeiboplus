export const languageProfiles = languages.map((l) => ({
  ...l,
  locale: locales[l.code],
  readiness: "planned" as Readiness,
  labels: Object.fromEntries(
    keys.map((key, i) => [key, labels[l.code][i]]),
  ) as Record<PhoneLabel, string>,
}));
export function languageProfile(code: string) {
  return languageProfiles.find((l) => l.code === code) || languageProfiles[0];
}
export function formatMoney(
  amount: number,
  currency = "JPY",
  locale = "en-US",
) {
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency,
    currencyDisplay: "narrowSymbol",
    maximumFractionDigits: 0,
  }).format(amount);
}
